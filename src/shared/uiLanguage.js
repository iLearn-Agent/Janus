export function normalizeUiLanguage(value = '') {
  return String(value || '').toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function translateSharedUiText(value = '', language = 'en') {
  const source = String(value || '');
  if (normalizeUiLanguage(language) !== 'en') return source;
  return SHARED_ENGLISH_EXACT[source] || source;
}

export function uiText(zh, en, language = 'en') {
  return normalizeUiLanguage(language) === 'en' ? String(en || '') : String(zh || '');
}

export function englishErrorFallback(error = null) {
  const code = String(error?.code || error?.body?.error?.code || error?.body?.code || '').trim();
  return `The operation could not be completed.${code ? ` (${code})` : ''} Please try again.`;
}
