export function userInitials(user = state.currentUser) {
  const text = user?.remark || user?.display_name || user?.displayName || user?.username || user?.email || user?.id || 'OP';
  return avatarLabelFromName(text);
}

export function avatarLabelFromName(value = '') {
  const text = String(value || '').trim();
  if (!text) return 'OP';
  const beforeEmail = text.split('@')[0] || text;
  const numericSuffix = beforeEmail.match(/(\d+)\s*$/);
  const stem = numericSuffix
    ? beforeEmail.slice(0, numericSuffix.index).replace(/[\s._-]+$/g, '')
    : beforeEmail;
  const compact = stem.replace(/[\s._-]+/g, '');
  const chinese = Array.from(compact.match(/[\u3400-\u9fff]/gu) || []);
  if (numericSuffix) {
    const digits = numericSuffix[1];
    if (digits.length >= 2) return digits.slice(-2);
    const words = stem.split(/[\s._-]+/).filter(Boolean);
    const leading = chinese[0] || Array.from(words[0] || compact)[0] || '';
    return `${leading}${digits}`.toUpperCase() || 'OP';
  }
  if (chinese.length >= 2) return chinese.slice(-2).join('');
  if (chinese.length === 1) return chinese[0];
  const words = stem.split(/[\s._-]+/).filter(Boolean);
  if (words.length >= 2) return words.slice(0, 2).map((part) => part[0]).join('').toUpperCase();
  return Array.from(compact || stem).slice(0, 2).join('').toUpperCase() || 'OP';
}
