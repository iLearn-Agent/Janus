export const DATABASE_MIGRATIONS = Object.freeze(definitions.map(([id, introducedIn, kind], index) => {
  const risk = Object.freeze({ ...legacyRiskDeclaration, ...(explicitRiskDeclarations[id] || {}) });
  return Object.freeze({
    id,
    introducedIn,
    kind,
    dependencies: index ? [definitions[index - 1][0]] : [],
    checksum: crypto.createHash('sha256').update(`janus-migration-v1:${id}:${introducedIn}:${kind}`).digest('hex'),
    riskChecksum: crypto.createHash('sha256').update(JSON.stringify(risk)).digest('hex'),
    riskDeclarationSource: explicitRiskDeclarations[id] ? 'explicit' : 'legacy_reviewed',
    risk,
  });
}));

export const DATABASE_MIGRATION_IDS = Object.freeze(DATABASE_MIGRATIONS.map((migration) => migration.id));

export function databaseMigrationIdsForVersion(appVersion = '') {
  const target = String(appVersion || '').trim();
  if (!target) return DATABASE_MIGRATION_IDS;
  return DATABASE_MIGRATIONS
    .filter((migration) => compareVersions(migration.introducedIn, target) <= 0)
    .map((migration) => migration.id);
}

export function databaseMigration(id = '') {
  return DATABASE_MIGRATIONS.find((migration) => migration.id === String(id || '')) || null;
}

export function assertDatabaseMigrationRegistry() {
  const ids = new Set();
  for (const migration of DATABASE_MIGRATIONS) {
    if (!migration.id || ids.has(migration.id)) throw new Error(`Invalid or duplicate database migration id: ${migration.id}`);
    for (const dependency of migration.dependencies) {
      if (!ids.has(dependency)) throw new Error(`Database migration ${migration.id} has an unresolved dependency: ${dependency}`);
    }
    assertMigrationRiskDeclaration(migration);
    ids.add(migration.id);
  }
  return true;
}

export function assertCloudDatabaseMigrationRegistry() {
  const ids = new Set();
  for (const migration of CLOUD_DATABASE_MIGRATIONS) {
    if (!migration.id || ids.has(migration.id)) throw new Error(`Invalid or duplicate cloud database migration id: ${migration.id}`);
    assertMigrationRiskDeclaration(migration);
    ids.add(migration.id);
  }
  return true;
}

export function assertMigrationRiskDeclaration(migration = {}) {
  const risk = migration.risk || {};
  for (const key of ['affectsTables', 'rewritesColumns', 'affectedUniqueKeys', 'preservationRules', 'requiredCapabilities']) {
    if (!Array.isArray(risk[key])) throw new Error(`Database migration ${migration.id || '<unknown>'} has invalid risk.${key}`);
  }
  if (!risk.collisionStrategy) throw new Error(`Database migration ${migration.id || '<unknown>'} is missing a collision strategy`);
  if (!risk.preservationRules.length) throw new Error(`Database migration ${migration.id || '<unknown>'} is missing preservation rules`);
  if (!Number.isInteger(Number(risk.minimumSyncProtocol || 0)) || Number(risk.minimumSyncProtocol || 0) < 1) {
    throw new Error(`Database migration ${migration.id || '<unknown>'} has invalid minimumSyncProtocol`);
  }
  if (risk.rewritesColumns.length && risk.collisionStrategy === 'not_applicable') {
    throw new Error(`Database migration ${migration.id || '<unknown>'} rewrites columns without a collision strategy`);
  }
  if (compareVersions(migration.introducedIn, '0.2.18') >= 0 && migration.riskDeclarationSource !== 'explicit') {
    throw new Error(`Database migration ${migration.id || '<unknown>'} requires an explicit risk declaration`);
  }
  if (risk.idempotent !== true || risk.rollbackSafe !== true) {
    throw new Error(`Database migration ${migration.id || '<unknown>'} must be idempotent and rollback safe`);
  }
  return true;
}

assertDatabaseMigrationRegistry();
assertCloudDatabaseMigrationRegistry();

function compareVersions(left = '', right = '') {
  const parts = (value) => String(value).replace(/^v/i, '').split(/[.-]/).slice(0, 3).map((item) => Number.parseInt(item, 10) || 0);
  const a = parts(left);
  const b = parts(right);
  for (let index = 0; index < 3; index += 1) {
    if ((a[index] || 0) !== (b[index] || 0)) return (a[index] || 0) > (b[index] || 0) ? 1 : -1;
  }
  return 0;
}
